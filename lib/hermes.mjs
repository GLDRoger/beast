import { readFileSync } from 'node:fs'
import { inHome, inPayload, GENERATED_MARKER } from './manifest.mjs'
import { writeGenerated } from './fsutil.mjs'

/**
 * Hermes reads ONE file — ~/.hermes/SOUL.md — as its identity slot. It has no
 * layering of its own onto beast's payloads, so that file is assembled at
 * install time from the codex payloads plus the Hermes overlay, rather than
 * symlinked: a link would force Hermes onto codex's exact wording, and a copy
 * drifts (it did — the roster went stale in it within weeks).
 *
 * The overlay names its replacements with @@KEY sentinels. Every sentinel must
 * match the payload exactly; one that no longer does fails the assembly, so
 * editing a payload without re-checking the overlay is a loud error instead of
 * a SOUL.md that quietly ships last month's roster.
 */

const SOUL_PATH = '.hermes/SOUL.md'

/** Parse the overlay into { key: replacement text }. */
function parseOverlay(text) {
  const blocks = {}
  let key = null
  for (const line of text.split('\n')) {
    if (line.startsWith('@@')) {
      key = line.slice(2).trim()
      blocks[key] = []
    } else if (key !== null) {
      blocks[key].push(line)
    }
  }
  return Object.fromEntries(
    Object.entries(blocks).map(([k, lines]) => [k, lines.join('\n').replace(/\n+$/, '')]),
  )
}

/** Swap the block between `startRe` and `endRe` (exclusive) for `replacement`. */
function replaceSection(text, { startRe, endRe, replacement, key }) {
  const start = text.search(startRe)
  if (start === -1) throw new Error(`hermes overlay @@${key}: start not found in payload`)
  const rest = text.slice(start)
  const endOffset = endRe ? rest.slice(1).search(endRe) + 1 : -1
  const end = endRe && endOffset > 0 ? start + endOffset : text.length
  return text.slice(0, start) + replacement + '\n\n' + text.slice(end).replace(/^\n+/, '')
}

/**
 * Build SOUL.md's text. Exported for tests: pure string in, string out.
 *
 * The generated marker rides in the Hermes header itself ("GENERATED by
 * `beast install`"), which is inside the first 512 bytes, so
 * `writeGenerated` recognises its own output on the next run.
 */
export function assembleSoul({ base, policy, overlay }) {
  const o = parseOverlay(overlay)

  let soul = base

  // Identity: the payload's first line ("You are Codex, an omnipotent agent.")
  // becomes the Hermes header, and the layered-instructions paragraph changes
  // because Hermes has no global/repo AGENTS.md layering of its own — the
  // policy rides inside this file.
  soul = soul.replace(/^[^\n]*\n/, o.HEADER + '\n')
  const layered = /# Layered instructions\n\n[\s\S]*?(?=\n# )/
  if (!layered.test(soul)) {
    throw new Error('hermes overlay @@LAYERED found no section in the base payload')
  }
  soul = soul.replace(
    layered,
    `# Layered instructions\n\n${o.LAYERED}\n`,
  )

  // The Mechanics block: Hermes's tool names, and the two lines that point at
  // the skill root and the delegation file.
  soul = replaceSection(soul, {
    key: 'MECHANICS',
    startRe: /# Mechanics\n\n/,
    endRe: /\n# /,
    replacement: `# Mechanics\n\n${o.MECHANICS}`,
  })

  // The policy's delegation intro addresses the harness itself; on Hermes that
  // is the operator, not one of the roster models. A payload edit that
  // invalidates the sentinel fails the build here, loudly, instead of
  // shipping a SOUL.md with a stale identity.
  const identity = /You are sol, the workhorse[\s\S]*?never to save effort\./
  if (!identity.test(policy)) {
    throw new Error('hermes overlay @@IDENTITY found no anchor in the policy payload')
  }
  const policyWithHermesIdentity = policy.replace(identity, o.IDENTITY)

  return (
    soul +
    '\n\n# Standing policy\n\n' +
    // Drop the policy's own "this file layers on" preface.
    policyWithHermesIdentity.replace(/^[^\n]*\n\n/, '')
  )
}

/**
 * Write ~/.hermes/SOUL.md. Called from install when the hermes harness is
 * selected. Returns the writeGenerated result so a refusal surfaces in the
 * report rather than exiting clean over a stale file.
 */
export function writeSoul() {
  const base = readFileSync(inPayload('codex/BEAST.v2.md'), 'utf8')
  const policy = readFileSync(inPayload('codex/AGENTS.md'), 'utf8')
  const overlay = readFileSync(inPayload('hermes/SOUL.overlay.md'), 'utf8')
  return writeGenerated(inHome(SOUL_PATH), assembleSoul({ base, policy, overlay }))
}
