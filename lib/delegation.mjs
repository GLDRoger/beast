import { HARNESSES, HARNESS_NAMES, inHome, GENERATED_MARKER } from './manifest.mjs'
import { writeGenerated } from './fsutil.mjs'
import { whichBinary } from './platform.mjs'

/**
 * Write ~/.beast/delegation.md listing the CLIs available for delegation.
 *
 * The policy files carry a delegation section that routes cross-vendor work through
 * agent-broker. That advice misfires for someone paying for one vendor or without the
 * broker installed, so this file is the authoritative list of what can actually be
 * reached, and of the path (broker or direct CLI) to reach it.
 *
 * ONLY AVAILABLE TOOLS ARE NAMED. An earlier version listed the absent ones with "do
 * NOT attempt codex exec, it is not installed", which is the wrong shape twice over: a
 * negative instruction naming a specific tool is more likely to surface in output than
 * to be silently obeyed, and models handle "here is the allowed set" far better than
 * "here is a forbidden set". Omission beats prohibition. Never reintroduce a list of
 * what is missing.
 *
 * The policy files are symlinks into the repo, so they cannot be rewritten per machine.
 * Generating one file they point at solves it, and re-running install self-corrects.
 */
const CALLS = {
  claude: '`claude -p --model <model>`',
  codex: '`codex exec` and `codex review`',
  grok: '`grok -p --model grok-4.6`',
  hermes: null, // no delegation CLI; filtered below
}

export function writeDelegation(available) {
  const have = HARNESS_NAMES.filter((n) => available.includes(n) && CALLS[n])

  const lines = [
    // Marker first, so writeGenerated can recognise its own output and back up anything
    // it did not write instead of truncating it.
    `<!-- ${GENERATED_MARKER} -->`,
    '',
    '# Delegation targets',
    '',
    'Generated by `beast install`. Re-run it after a subscription changes.',
    '',
    'This is the authoritative list of what is available for delegation on this machine.',
    '',
  ]

  // The policy files route all delegation through agent-broker. On a machine where the
  // broker binary exists, name it as the path and list the providers it can reach; on
  // one where it doesn't, fall back to the direct CLI forms without mentioning the
  // broker at all — omission beats prohibition here exactly as it does for absent CLIs.
  const broker = have.length > 0 && whichBinary('broker')

  if (broker) {
    lines.push(
      'Delegation on this machine runs through **agent-broker** (`broker` CLI; the same',
      'surface is the `agent-broker` MCP server where registered). Providers reachable',
      'through it:',
      '',
    )
    for (const n of have) lines.push(`- **${HARNESSES[n].label}** (\`broker send <chat> --to ${n} ...\`)`)
    lines.push(
      '',
      'Delegate outward only to the providers listed above. Where a routing rule',
      'elsewhere names a model whose provider is not on this list, use a model you can',
      'reach directly through the Agent or Workflow model parameter, or do the work',
      'inline.',
      '',
    )
  } else if (have.length) {
    for (const n of have) lines.push(`- **${HARNESSES[n].label}** — invoke as ${CALLS[n]}`)
    lines.push(
      '',
      'Delegate outward only to the tools listed above. Where a routing rule elsewhere',
      'names a tool that is not on this list, use a model you can reach directly through',
      'the Agent or Workflow model parameter, or do the work inline.',
      '',
    )
  } else {
    lines.push(
      'No external CLI is configured for delegation. Handle work with the current tool,',
      'using its own sub-agents where that helps.',
      '',
    )
  }

  const path = inHome('.beast/delegation.md')
  // Pass the result through. Swallowing it meant a failed write still reported an
  // install that had configured routing it never actually wrote.
  return { ...writeGenerated(path, lines.join('\n')), path, have }
}
