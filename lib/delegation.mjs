import { HARNESSES, HARNESS_NAMES, inHome } from './manifest.mjs'
import { writeGenerated } from './fsutil.mjs'

/**
 * Write ~/.beast/delegation.md listing the CLIs available for delegation.
 *
 * The policy files carry a model-routing table and tell the agent to hand bulk work to
 * another CLI. That advice misfires for someone paying for one vendor, so this file is
 * the authoritative list of what can actually be reached.
 *
 * ONLY AVAILABLE TOOLS ARE NAMED. An earlier version listed the absent ones with "do
 * NOT attempt codex exec, it is not installed", which is the wrong shape twice over: a
 * negative instruction naming a specific tool is more likely to surface in output than
 * to be silently obeyed, and models handle "here is the allowed set" far better than
 * "here is a forbidden set". Omission beats prohibition. Never reintroduce a list of
 * what is missing.
 *
 * The policy files are symlinks into the repo, so they cannot be rewritten per machine.
 * Generating one file they point at solves it, and re-running install self-corrects.
 */
const CALLS = {
  claude: '`claude -p --model <model>`',
  codex: '`codex exec` and `codex review`',
  grok: '`grok -p --model grok-4.5`',
}

export function writeDelegation(available) {
  const have = HARNESS_NAMES.filter((n) => available.includes(n))

  const lines = [
    '# Delegation targets',
    '',
    'Generated by `beast install`. Re-run it after a subscription changes.',
    '',
    'This is the authoritative list of CLIs available for delegation on this machine.',
    '',
  ]

  if (have.length) {
    for (const n of have) lines.push(`- **${HARNESSES[n].label}** — invoke as ${CALLS[n]}`)
    lines.push(
      '',
      'Delegate outward only to the tools listed above. Where a routing rule elsewhere',
      'names a tool that is not on this list, use a model you can reach directly through',
      'the Agent or Workflow model parameter, or do the work inline.',
      '',
    )
  } else {
    lines.push(
      'No external CLI is configured for delegation. Handle work with the current tool,',
      'using its own sub-agents where that helps.',
      '',
    )
  }

  const path = inHome('.beast/delegation.md')
  writeGenerated(path, lines.join('\n'))
  return { path, have }
}
