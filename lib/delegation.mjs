import { writeFileSync, mkdirSync } from 'node:fs'
import { dirname } from 'node:path'
import { HARNESSES, HARNESS_NAMES, inHome } from './manifest.mjs'

/**
 * Write ~/.beast/delegation.md from the CLIs the user says they have.
 *
 * The policy files (CLAUDE.md, AGENTS.md) carry a model-routing table and tell the
 * agent to hand bulk work to another CLI: `codex exec` from Claude, `claude -p` from
 * Codex. That advice is actively harmful to someone who only pays for one of them.
 * They get standing instructions to shell out to a binary that does not exist, burn a
 * turn discovering it, and conclude the config is broken.
 *
 * The policy files are symlinks into the repo, so install cannot rewrite them per
 * machine. Generating one small file the policy points at solves it without breaking
 * the link model, and it self-corrects: buy a subscription, re-run install.
 */
const CALLS = {
  claude: '`claude -p --model <model>`',
  codex: '`codex exec` / `codex review`',
  grok: '`grok -p --model grok-4.5`',
}

export function writeDelegation(available) {
  const have = HARNESS_NAMES.filter((n) => available.includes(n))
  const missing = HARNESS_NAMES.filter((n) => !available.includes(n))

  const lines = [
    '# Available CLIs on this machine',
    '',
    'Generated by `beast install`. Re-run it after adding or removing a subscription.',
    '',
    '**Consult this before delegating work to another CLI.** The routing guidance in',
    'CLAUDE.md and AGENTS.md assumes all three exist. On this machine, only the ones',
    'listed as available do.',
    '',
  ]

  if (have.length) {
    lines.push('## Available', '')
    for (const n of have) lines.push(`- **${HARNESSES[n].label}** — invoke as ${CALLS[n]}`)
    lines.push('')
  }

  if (missing.length) {
    lines.push('## Not available', '')
    for (const n of missing) {
      lines.push(`- **${HARNESSES[n].label}** — do NOT attempt ${CALLS[n]}. It is not installed.`)
    }
    lines.push(
      '',
      'Do not treat these as fallbacks and do not suggest the user install them mid-task.',
      'Route the work to a model you can already reach, or do it yourself.',
      '',
    )
  }

  if (have.length === 1) {
    lines.push(
      '## Single-CLI setup',
      '',
      `Only ${HARNESSES[have[0]].label} is available, so **ignore every cross-CLI`,
      'delegation rule in the policy files.** Sub-agents within this CLI still work',
      'normally; shelling out to a different vendor does not.',
      '',
    )
  }

  const path = inHome('.beast/delegation.md')
  mkdirSync(dirname(path), { recursive: true })
  writeFileSync(path, lines.join('\n'))
  return { path, have, missing }
}
