import { test } from 'node:test'
import assert from 'node:assert/strict'
import { readFileSync } from 'node:fs'
import { join } from 'node:path'
import { REPO } from '../lib/manifest.mjs'
import { assembleSoul } from '../lib/hermes.mjs'

const payload = (rel) => readFileSync(join(REPO, 'home', rel), 'utf8')

function inputs() {
  return {
    base: payload('codex/BEAST.v2.md'),
    policy: payload('codex/AGENTS.md'),
    overlay: payload('hermes/SOUL.overlay.md'),
  }
}

test('assembleSoul produces the Hermes SOUL from the shared payloads', () => {
  const soul = assembleSoul(inputs())
  // The generated marker is inside the first 512 bytes so writeGenerated
  // recognises its own output on the next install.
  assert.ok(soul.slice(0, 512).includes('generated by beast install'))
  assert.ok(soul.includes('You are Hermes Agent, running the beast system.'))
  // Harness-specific identity and mechanics compose around the stable Beast
  // body without copying a volatile provider roster into the prompt.
  assert.ok(soul.includes('read_file'))
  assert.ok(soul.includes('active Hermes profile'))
  assert.ok(soul.includes('agent-broker MCP'))
  assert.ok(soul.includes('headless CLI'))
  assert.ok(soul.includes('~/.beast/delegation.md'))
  assert.ok(!soul.includes('grok-4.6'))
  assert.ok(!soul.includes('gpt-5.6-terra'))
  // The policy rides inside the file under its own heading.
  assert.ok(soul.includes('# Standing policy'))
})

test('assembleSoul fails loudly when a payload edit invalidates an overlay anchor', () => {
  const broken = inputs()
  broken.base = broken.base.replace('## Intent and scope', '## Missing body anchor')
  assert.throws(() => assembleSoul(broken), /@@HEADER/)
})
